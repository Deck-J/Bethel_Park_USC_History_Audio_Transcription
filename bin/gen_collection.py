#!/usr/bin/env python3
"""Generate docs/COLLECTION.md from the recordings themselves.

The index is derived, never hand-maintained: every row comes from a recording's metadata.json, so the
document cannot claim a recording that is not there, or miss one that is. Run it after adding or
updating a recording, and commit the result with it.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "COLLECTION.md"


def human_duration(seconds):
    total = int(round(seconds))
    h, rem = divmod(total, 3600)
    m, s = divmod(rem, 60)
    if h:
        return f"{h} h {m:02d} m"
    return f"{m} m {s:02d} s"


def word_count(folder, side):
    rel = side.get("transcript")
    if not rel:
        return 0
    p = folder / rel
    if not p.is_file():
        return 0
    return len(p.read_text(encoding="utf-8").split())


def main():
    rows = []
    for folder in sorted((ROOT / "recordings").iterdir()):
        meta_p = folder / "metadata.json"
        if not folder.is_dir() or not meta_p.is_file():
            continue
        meta = json.loads(meta_p.read_text(encoding="utf-8"))
        kind = meta.get("kind", "recording")
        sides = meta.get("sides", [])
        minutes = sum(s.get("duration_s", 0) for s in sides) / 60.0
        words = sum(word_count(folder, s) for s in sides) if sides else 0
        if kind == "documents":
            words = sum(
                len(p.read_text(encoding="utf-8").split())
                for p in folder.glob("*.md")
                if p.name != "README.md"
            )
        speakers = ", ".join(s.get("name", "?") for s in meta.get("speakers", []))
        rows.append(
            {
                "folder": folder.name,
                "title": meta.get("title", folder.name),
                "date": meta.get("date", "unknown"),
                "date_known": meta.get("date") not in (None, "", "unknown"),
                "kind": kind,
                "minutes": minutes,
                "words": words,
                "speakers": speakers,
                "engine": meta.get("transcript", {}).get("engine", "unknown"),
                "rights": meta.get("rights", {}).get("status", "unknown"),
            }
        )

    rows.sort(key=lambda r: (not r["date_known"], r["date"], r["folder"]))

    rec = [r for r in rows if r["kind"] == "recording"]
    docs = [r for r in rows if r["kind"] == "documents"]
    total_min = sum(r["minutes"] for r in rec)
    total_words = sum(r["words"] for r in rows)

    lines = [
        "# The collection",
        "",
        "Every item held in the Historical Room's oral-history collection and packaged here, derived from",
        "the recordings' own `metadata.json` — this file is generated by `bin/gen_collection.py`, so it",
        "cannot drift from what is actually in the repository.",
        "",
        f"**{len(rows)} items** — {len(rec)} recordings totalling **{human_duration(total_min * 60)}** of",
        f"audio, and {len(docs)} papers-only item(s); **{total_words:,} words** of transcript.",
        "",
        "##### Recordings",
        "",
        "| item | date | length | words | speaker(s) |",
        "|---|---|---|---|---|",
    ]
    for r in rec:
        date = r["date"] if r["date_known"] else "unknown"
        lines.append(
            f"| [{r['title']}](recordings/{r['folder']}/) | {date} | {human_duration(r['minutes'] * 60)} "
            f"| {r['words']:,} | {r['speakers']} |"
        )

    if docs:
        lines += [
            "",
            "##### Papers and documents",
            "",
            "| item | date | words | what it is |",
            "|---|---|---|---|",
        ]
        for r in docs:
            lines.append(
                f"| [{r['title']}](recordings/{r['folder']}/) | {r['date']} | {r['words']:,} "
                f"| transcripts and notes with no audio of their own |"
            )

    unknown = [r for r in rows if not r["date_known"]]
    lines += ["", "## Dating", ""]
    if unknown:
        lines.append(
            f"{len(unknown)} item(s) carry no established date. They are filed as `unknown-…`, and each"
            " one's `date_source` records what was searched — the tape itself, its labels, the"
            " transcript's opening lines — rather than a date inferred from a folder name. If you can"
            " date one of them from a cassette in hand, that is the most useful correction you can"
            " contribute: open an issue with what the label says."
        )
    else:
        lines.append("Every item here carries a date established from the material itself.")

    lines += [
        "",
        "## Rights",
        "",
        "All items are public domain, released by the rights holder; transcripts are CC0 1.0. The claim is",
        "per item — see `docs/RIGHTS.md`.",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(rec)} recordings, {len(docs)} documents, "
          f"{human_duration(total_min * 60)}, {total_words:,} words")
    return 0


if __name__ == "__main__":
    sys.exit(main())
